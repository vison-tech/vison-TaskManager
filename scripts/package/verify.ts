import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { lstat, mkdtemp, readdir, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, relative } from 'node:path';
import { cleanRuntimeEnvironment } from './runtime.ts';

const execute = promisify(execFile);
const entries = new Set(['desktop/index', 'desktop/gui', 'desktop/selfcheck', 'server/index', 'host/inject'].map((entry) => `apps/${entry}.mjs`));

export async function assertPackageContents(app: string): Promise<void> {
  const resources = join(app, 'Contents/Resources');
  const visit = async (directory: string): Promise<void> => {
    for (const name of await readdir(directory)) {
      const path = join(directory, name);
      const stat = await lstat(path);
      const file = relative(resources, path).split('\\').join('/');
      if (stat.isSymbolicLink()) throw new Error(`Packaged resources contain a symlink: ${file}`);
      if (stat.isDirectory()) { await visit(path); continue; }
      const allowed = file === 'node' || file === 'app/build-info.json' || file.startsWith('licenses/')
        || file.startsWith('app/dist/web/') || (file.startsWith('app/') && entries.has(file.slice(4)));
      if (!allowed || /(?:^|\/)(?:\.env(?:\..*)?|launcher\.json|state\.json|node_modules)(?:\/|$)|\.sqlite(?:-wal|-shm)?$/.test(file)) {
        throw new Error(`Unexpected file in application resources: ${file}`);
      }
    }
  };
  await visit(resources);
  // Dist is generated by Vite. Reject source maps that could disclose original paths.
  const webFiles = await readdir(join(resources, 'app/dist/web/assets'));
  if (webFiles.some((name) => name.endsWith('.map'))) throw new Error('Release assets must not contain source maps.');
}

/** Move a copy out of the checkout and use a PATH containing no npm, Node or tsx. */
export async function verifyRelocatedApplication(app: string): Promise<Record<string, unknown>> {
  const temporary = await mkdtemp(join(tmpdir(), 'taskmanager-relocated-'));
  try {
    const moved = join(temporary, 'TaskManaer-Vison.app');
    await execute('/usr/bin/ditto', [app, moved], { timeout: 90_000 });
    await execute('/usr/bin/codesign', ['--verify', '--deep', '--strict', moved], { timeout: 30_000 });
    const resources = join(moved, 'Contents/Resources');
    const executable = join(resources, 'node');
    const env = cleanRuntimeEnvironment();
    // No inherited instance, agent, credential or launcher settings enter the fixture.
    for (const key of Object.keys(env)) if (/^TASKMANAGER_|^PORT$|^HOST$/.test(key)) delete env[key];
    const options = { env, cwd: temporary, timeout: 30_000, maxBuffer: 2 * 1024 * 1024 };
    await execute(join(moved, 'Contents/MacOS/TaskManager'), ['--check-resources'], options);
    await execute(executable, [join(resources, 'app/apps/desktop/index.mjs'), '--help'], options);
    const { stdout } = await execute(executable, [join(resources, 'app/apps/desktop/selfcheck.mjs')], options);
    const check = JSON.parse(stdout.trim()) as Record<string, unknown>;
    if (check.ok !== true || check.sqlite !== true || check.web !== true || check.persistence !== true) {
      throw new Error('Relocated package did not pass the SQLite/Web persistence check.');
    }
    // Readability also verifies the unsigned manifest survived relocation and sealing.
    await readFile(join(resources, 'app/build-info.json'), 'utf8');
    return { ...check, relocated: true, signatureAfterRelocation: true, systemNode: false, hostStarted: false };
  } finally { await rm(temporary, { recursive: true, force: true }); }
}
